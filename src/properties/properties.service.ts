import {
  ForbiddenException,
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository, SelectQueryBuilder } from 'typeorm';
import { Property } from './property.entity';
import { FilterPropertyDto } from './filter-property.dto';
import { MapBoundsDto } from './map-bounds.dto';
import { PropertyWriteDto } from './property-write.dto';
import { ConfigService } from '@nestjs/config';
import { publicPropertyImageVariants, removePropertyDocumentFiles, removePropertyImageFiles } from './property-images';

/** Hard ceiling on pins returned for one map viewport. */
const MAP_RESULT_LIMIT = 300;

/**
 * Ceiling on the unpaginated pin set.
 *
 * A pin is ~120 bytes, so 5 000 is well under a megabyte — but a map cannot usefully render more
 * than a few hundred markers anyway, and this stops a single request from streaming the whole
 * table if the portfolio ever grows past what the UI can draw. When this limit starts biting,
 * clustering or server-side tile aggregation is the answer, not a bigger number.
 */
const PIN_LIMIT = 5000;

/** The only columns a map marker needs: no images, no owner, no description. */
const PIN_COLUMNS = [
  'property.id',
  'property.title',
  'property.price',
  'property.propertyType',
  'property.city',
  'property.location',
  'property.latitude',
  'property.longitude',
  // TypeORM includes the sort key in the DISTINCT wrapper generated by take() with a join.
  'property.createdAt',
];

const LIST_COLUMNS = [
  'property.id',
  'property.title',
  'property.price',
  'property.city',
  'property.location',
  'property.propertyType',
  'property.bedrooms',
  'property.bathrooms',
  'property.area',
  'property.images',
  'property.transactionType',
  'property.status',
  'property.visibility',
  'property.priceUnit',
  'property.featured',
  'property.amenities',
  'property.documents',
  'property.floor',
  'property.workstations',
  'property.parkingSpaces',
  // Coordinates ship with every list row so the map beside the list can plot the same
  // result set without a second round trip.
  'property.latitude',
  'property.longitude',
  'property.createdAt',
  // owner fields — safe subset only
  'owner.id',
  'owner.name',
  'owner.email',
];

@Injectable()
export class PropertiesService {
  constructor(
    private configService: ConfigService,

    @InjectRepository(Property)
    private propertyRepo: Repository<Property>,
  ) {}

  // ── CREATE ───────────────────────────────────────────────
  async create(data: Partial<Property>) {
    const property = this.propertyRepo.create(data);
    const saved = await this.propertyRepo.save(property);
    return this.findOne(String(saved.id), true);
  }

  async findFeatured() {
    const rows = await this.propertyRepo.createQueryBuilder('property')
      .leftJoin('property.owner', 'owner').select(LIST_COLUMNS)
      .where('property.visibility = :visibility', { visibility: 'published' })
      .andWhere('property.featured = :featured', { featured: true })
      .orderBy('property.createdAt', 'DESC').take(6).getMany();
    return rows.map((row) => this.appendImageUrls(row));
  }

  // ── FACETS ───────────────────────────────────────────────
  /**
   * Distinct values behind the listing filters, plus the real price envelope.
   *
   * Without this the UI can only offer the values present on the page it happens to have
   * loaded, so a type that exists on page 4 is unreachable from page 1. Cheap enough to call
   * once per listing visit: three grouped scans over an indexed table.
   */
  async findFacets() {
    const [types, cities, bounds] = await Promise.all([
      this.propertyRepo
        .createQueryBuilder('property')
        .select('property.propertyType', 'value')
        .addSelect('COUNT(property.id)', 'count')
        .where('property.visibility = :visibility', { visibility: 'published' })
        .andWhere('property.propertyType IS NOT NULL')
        .andWhere("property.propertyType <> ''")
        .groupBy('property.propertyType')
        .orderBy('property.propertyType', 'ASC')
        .getRawMany<{ value: string; count: string }>(),

      this.propertyRepo
        .createQueryBuilder('property')
        .select('property.city', 'value')
        .addSelect('COUNT(property.id)', 'count')
        .where('property.visibility = :visibility', { visibility: 'published' })
        .andWhere('property.city IS NOT NULL')
        .andWhere("property.city <> ''")
        .groupBy('property.city')
        .orderBy('property.city', 'ASC')
        .getRawMany<{ value: string; count: string }>(),

      this.propertyRepo
        .createQueryBuilder('property')
        .select('MIN(property.price)', 'min')
        .addSelect('MAX(property.price)', 'max')
        .where('property.visibility = :visibility', { visibility: 'published' })
        .getRawOne<{ min: string | null; max: string | null }>(),
    ]);

    const toFacet = (rows: { value: string; count: string }[]) =>
      rows.map((r) => ({ value: r.value, count: Number(r.count) }));

    return {
      propertyTypes: toFacet(types),
      cities: toFacet(cities),
      priceRange: {
        min: Number(bounds?.min ?? 0),
        max: Number(bounds?.max ?? 0),
      },
    };
  }

  // ── LIST (public + my-properties) ────────────────────────
  async findAll(query: FilterPropertyDto, includeDraft = false) {
    const page = Math.max(1, Number(query.page || 1));
    const limit = Math.min(48, Math.max(1, Number(query.limit || 12)));

    const qb = this.propertyRepo
      .createQueryBuilder('property')
      .leftJoin('property.owner', 'owner')
      .select(LIST_COLUMNS);

    if (!includeDraft) qb.where('property.visibility = :visibility', { visibility: 'published' });

    // Scope to one owner (used by dashboard "my properties")
    if (query.ownerId) {
      qb.andWhere('owner.id = :ownerId', { ownerId: Number(query.ownerId) });
    }

    this.applyFilters(qb, query);
    this.applySort(qb, query.sort);

    qb.skip((page - 1) * limit).take(limit);

    const [data, total] = await qb.getManyAndCount();

    const transformed = data.map((p) => this.appendImageUrls(p));

    return {
      data: transformed,
      total,
      page,
      limit,
      totalPages: Math.ceil(total / limit),
    };
  }

  // ── DETAIL ───────────────────────────────────────────────
  async findOne(id: string, includeDraft = false) {
    const query = this.propertyRepo
      .createQueryBuilder('property')
      .leftJoin('property.owner', 'owner')
      .addSelect(['owner.id', 'owner.name', 'owner.email'])
      .where('property.id = :id', { id: parseInt(id) });
    if (!includeDraft) query.andWhere('property.visibility = :visibility', { visibility: 'published' });
    const property = await query.getOne();

    if (!property) throw new NotFoundException('Property not found');
    return this.appendImageUrls(property);
  }

  // ── UPDATE (owner or admin only) ─────────────────────────
  async update(
    id: number,
    body: PropertyWriteDto,
    files: { images?: Express.Multer.File[]; documents?: Express.Multer.File[] },
    requestingUser: { id: number; role: string },
  ) {
    const existing = await this.propertyRepo.findOne({
      where: { id },
      relations: ['owner'],
    });

    if (!existing) throw new NotFoundException('Property not found');

    this.assertOwnerOrAdmin(existing, requestingUser);

    const keptUrls: string[] = body.keepImages
      ? Array.isArray(body.keepImages)
        ? body.keepImages
        : [body.keepImages]
      : [];
    const kept = keptUrls.map((value) => {
      try {
        return decodeURIComponent(new URL(value, 'http://local').pathname.split('/').pop() ?? '');
      } catch {
        return value.split('/').pop() ?? value;
      }
    }).filter((value) => Boolean(value) && (existing.images ?? []).includes(value));

    const newImages = files?.images?.map((f) => f.filename) ?? [];

    const images = [...kept, ...newImages];
    const { keepImages, ...raw } = body;
    const numeric = ['price', 'area', 'bedrooms', 'bathrooms', 'latitude', 'longitude', 'workstations', 'parkingSpaces'];
    const rest = Object.fromEntries(
      Object.entries(raw).map(([key, value]) => [key, numeric.includes(key) ? Number(value) : value]),
    );

    const keptDocuments = (body.documents ?? []).filter((document) =>
      (existing.documents ?? []).some((saved) => saved.url === document.url && saved.title === document.title),
    );

    await this.propertyRepo.save({
      ...existing,
      ...rest,
      images,
      documents: [
        ...keptDocuments,
        ...(files.documents ?? []).map((file) => ({
          title: file.originalname,
          url: `/uploads/${file.filename}`,
        })),
      ],
    });
    const removedImages = (existing.images ?? []).filter((filename) => !images.includes(filename));
    const removedDocuments = (existing.documents ?? []).filter(
      (document) => !keptDocuments.some((kept) => kept.url === document.url),
    );
    await Promise.all([
      removePropertyImageFiles(removedImages),
      removePropertyDocumentFiles(removedDocuments.map((document) => document.url)),
    ]);
    return this.findOne(String(id), true);
  }

  // ── DELETE (owner or admin only) ─────────────────────────
  async remove(id: string, requestingUser: { id: number; role: string }) {
    const property = await this.propertyRepo.findOne({
      where: { id: parseInt(id) },
      relations: ['owner'],
    });

    if (!property) throw new NotFoundException('Property not found');

    this.assertOwnerOrAdmin(property, requestingUser);

    await this.propertyRepo.remove(property);
    await Promise.all([
      removePropertyImageFiles(property.images ?? []),
      removePropertyDocumentFiles((property.documents ?? []).map((document) => document.url)),
    ]);
    return { message: 'Property removed successfully' };
  }

  // ── MAP BOUNDS ───────────────────────────────────────────
  /**
   * Every listing matching the filters, as map markers, with no pagination.
   *
   * This is deliberately separate from `findAll`: the list is paged because a visitor reads it a
   * page at a time, but a map is only honest if it shows the whole result set — a map plotting
   * page 1 of 9 tells the visitor there are six properties in the city.
   *
   * Listings without coordinates are excluded here rather than filtered client-side, so the count
   * the UI reports is the count it can actually draw.
   */
  async findPins(query: FilterPropertyDto) {
    const qb = this.propertyRepo
      .createQueryBuilder('property')
      .leftJoin('property.owner', 'owner')
      .select(PIN_COLUMNS)
      .where('property.latitude IS NOT NULL')
      .andWhere('property.visibility = :visibility', { visibility: 'published' })
      .andWhere('property.longitude IS NOT NULL')
      // 0,0 is Null Island in the Gulf of Guinea — what an unset numeric column looks like.
      .andWhere('NOT (property.latitude = 0 AND property.longitude = 0)');

    if (query.ownerId) {
      qb.andWhere('owner.id = :ownerId', { ownerId: Number(query.ownerId) });
    }

    this.applyFilters(qb, query);
    this.applySort(qb, query.sort);
    qb.take(PIN_LIMIT);

    const pins = await qb.getMany();

    return {
      data: pins.map((pin) => ({
        id: pin.id,
        title: pin.title,
        price: pin.price,
        propertyType: pin.propertyType,
        city: pin.city,
        location: pin.location,
        latitude: pin.latitude as number,
        longitude: pin.longitude as number,
      })),
      /** Pins actually returned, which is the count the map can draw. */
      total: pins.length,
      /** True when the ceiling clipped the result, so the UI can say the map is partial. */
      truncated: pins.length === PIN_LIMIT,
    };
  }

  async findWithinBounds(bounds: MapBoundsDto) {
    const qb = this.propertyRepo
      .createQueryBuilder('property')
      .leftJoin('property.owner', 'owner')
      .select(LIST_COLUMNS)
      .where('property.latitude  BETWEEN :south AND :north', {
        south: bounds.south,
        north: bounds.north,
      })
      .andWhere('property.visibility = :visibility', { visibility: 'published' })
      .andWhere('property.longitude BETWEEN :west AND :east', {
        west: bounds.west,
        east: bounds.east,
      })
      // Same Null Island exclusion as `findPins`: the write path stores 0 for an unset
      // coordinate, so a viewport over the Gulf of Guinea would otherwise return every
      // unmapped listing in the portfolio.
      .andWhere('NOT (property.latitude = 0 AND property.longitude = 0)');

    if (bounds.ownerId) {
      qb.andWhere('owner.id = :ownerId', { ownerId: Number(bounds.ownerId) });
    }

    this.applyFilters(qb, bounds);
    this.applySort(qb, bounds.sort);

    // A zoomed-right-out viewport would otherwise ask for the entire table. The map cannot
    // usefully render more pins than this anyway, and the list beside it paginates separately.
    qb.take(MAP_RESULT_LIMIT);

    const properties = await qb.getMany();
    return properties.map((p) => this.appendImageUrls(p));
  }

  // ── PRIVATE ──────────────────────────────────────────────
  /**
   * The filter clauses shared by the paginated list and the map viewport, so the two views can
   * never disagree about what "Warehouse under $2M in Austin" means.
   */
  private applyFilters(
    qb: SelectQueryBuilder<Property>,
    query: Pick<
      FilterPropertyDto,
      'search' | 'city' | 'propertyType' | 'minPrice' | 'maxPrice' | 'bedrooms'
    >,
  ) {
    if (query.search?.trim()) {
      qb.andWhere(
        `(LOWER(property.title)        LIKE LOWER(:s)
          OR LOWER(property.city)       LIKE LOWER(:s)
          OR LOWER(property.location)   LIKE LOWER(:s)
          OR LOWER(property.propertyType) LIKE LOWER(:s))`,
        { s: `%${query.search.trim()}%` },
      );
    }

    if (query.city?.trim()) {
      qb.andWhere('LOWER(property.city) LIKE LOWER(:city)', {
        city: `%${query.city.trim()}%`,
      });
    }

    if (query.propertyType?.trim()) {
      // Case-insensitive exact match: the filter dropdown is populated from stored values,
      // but a trailing space or different casing must not silently return zero results.
      qb.andWhere('LOWER(property.propertyType) = LOWER(:pt)', {
        pt: query.propertyType.trim(),
      });
    }

    if (query.minPrice) {
      qb.andWhere('property.price >= :min', { min: Number(query.minPrice) });
    }

    if (query.maxPrice) {
      qb.andWhere('property.price <= :max', { max: Number(query.maxPrice) });
    }

    if (query.bedrooms) {
      qb.andWhere('property.bedrooms >= :bed', { bed: Number(query.bedrooms) });
    }
  }

  private applySort(qb: SelectQueryBuilder<Property>, sort?: string) {
    switch (sort) {
      case 'price_asc':
        qb.orderBy('property.price', 'ASC');
        break;
      case 'price_desc':
        qb.orderBy('property.price', 'DESC');
        break;
      default:
        qb.orderBy('property.createdAt', 'DESC');
        break;
    }
  }

  private assertOwnerOrAdmin(
    property: Property,
    user: { id: number; role: string },
  ) {
    const isOwner = Number(property.owner?.id) === Number(user.id);
    const isAdmin = user.role === 'admin';

    if (!isOwner && !isAdmin) {
      throw new ForbiddenException('You do not own this property');
    }
  }

  private appendImageUrls(property: Property) {
    const baseUrl = (this.configService.get<string>('BASE_URL') ?? 'http://api.local.test:3000').replace(/\/$/, '');

    return {
      ...property,
      images: property.images?.map((img) => /^https?:\/\//.test(img) ? img : `${baseUrl}/uploads/${img}`) ?? [],
      imageVariants: property.images?.filter((img) => !/^https?:\/\//.test(img)).map((img) => publicPropertyImageVariants(img, baseUrl)) ?? [],
      documents: property.documents?.map((document) => ({
        ...document,
        url: /^https?:\/\//.test(document.url) ? document.url : `${baseUrl}${document.url}`,
      })) ?? [],
    };
  }
}
